/// A tiny JSON reader and a validator for the schema subset, independent of
/// the code under test. Numbers keep their text.
mod j {
    #[derive(Debug, Clone, PartialEq)]
    pub enum V {
        Null,
        Bool(bool),
        Num(String),
        Str(String),
        Arr(Vec<V>),
        Obj(Vec<(String, V)>),
    }

    impl V {
        pub fn get(&self, k: &str) -> &V {
            self.get_opt(k).unwrap_or_else(|| panic!("no key {k:?} in {self:?}"))
        }
        pub fn get_opt(&self, k: &str) -> Option<&V> {
            self.obj().iter().find(|(a, _)| a == k).map(|(_, v)| v)
        }
        pub fn obj(&self) -> &Vec<(String, V)> {
            match self {
                V::Obj(kv) => kv,
                _ => panic!("not an object: {self:?}"),
            }
        }
        pub fn str(&self) -> &str {
            match self {
                V::Str(s) => s,
                _ => panic!("not a string: {self:?}"),
            }
        }
        pub fn bool(&self) -> bool {
            match self {
                V::Bool(b) => *b,
                _ => panic!("not a bool: {self:?}"),
            }
        }
        pub fn i64(&self) -> i64 {
            match self {
                V::Num(n) => n.parse().unwrap_or_else(|_| panic!("not an integer: {n}")),
                _ => panic!("not a number: {self:?}"),
            }
        }
        pub fn arr(&self) -> &Vec<V> {
            match self {
                V::Arr(a) => a,
                _ => panic!("not an array: {self:?}"),
            }
        }
    }

    pub fn parse(s: &str) -> V {
        try_parse(s).unwrap_or_else(|e| panic!("{e}: {s:?}"))
    }

    pub fn try_parse(s: &str) -> Result<V, String> {
        let b = s.as_bytes();
        let mut i = 0;
        let v = val(b, &mut i)?;
        ws(b, &mut i);
        if i != b.len() {
            return Err(format!("trailing characters at {i}"));
        }
        Ok(v)
    }

    fn ws(b: &[u8], i: &mut usize) {
        while *i < b.len() && matches!(b[*i], b' ' | b'\n' | b'\t' | b'\r') {
            *i += 1;
        }
    }

    fn val(b: &[u8], i: &mut usize) -> Result<V, String> {
        ws(b, i);
        let c = *b.get(*i).ok_or("unexpected end")?;
        match c {
            b'{' | b'[' => {
                let close = if c == b'{' { b'}' } else { b']' };
                *i += 1;
                let mut kv = Vec::new();
                let mut a = Vec::new();
                ws(b, i);
                if b.get(*i) == Some(&close) {
                    *i += 1;
                    return Ok(if c == b'{' { V::Obj(kv) } else { V::Arr(a) });
                }
                loop {
                    if c == b'{' {
                        let V::Str(k) = val(b, i)? else { return Err("key is not a string".into()) };
                        ws(b, i);
                        if b.get(*i) != Some(&b':') {
                            return Err("':' expected".into());
                        }
                        *i += 1;
                        kv.push((k, val(b, i)?));
                    } else {
                        a.push(val(b, i)?);
                    }
                    ws(b, i);
                    match b.get(*i) {
                        Some(b',') => *i += 1,
                        Some(x) if *x == close => {
                            *i += 1;
                            return Ok(if c == b'{' { V::Obj(kv) } else { V::Arr(a) });
                        }
                        _ => return Err(format!("',' or close expected at {i}")),
                    }
                }
            }
            b'"' => {
                *i += 1;
                let mut s = Vec::new();
                loop {
                    let c = *b.get(*i).ok_or("unterminated string")?;
                    *i += 1;
                    match c {
                        b'"' => break,
                        b'\\' => {
                            let e = *b.get(*i).ok_or("bad escape")?;
                            *i += 1;
                            match e {
                                b'"' | b'\\' | b'/' => s.push(e),
                                b'b' => s.push(8),
                                b'f' => s.push(12),
                                b'n' => s.push(b'\n'),
                                b'r' => s.push(b'\r'),
                                b't' => s.push(b'\t'),
                                b'u' => {
                                    let h = std::str::from_utf8(b.get(*i..*i + 4).ok_or("short \\u")?).map_err(|_| "bad \\u")?;
                                    let cp = u32::from_str_radix(h, 16).map_err(|_| "bad \\u")?;
                                    *i += 4;
                                    let ch = char::from_u32(cp).unwrap_or('\u{FFFD}');
                                    let mut buf = [0u8; 4];
                                    s.extend_from_slice(ch.encode_utf8(&mut buf).as_bytes());
                                }
                                _ => return Err("bad escape".into()),
                            }
                        }
                        c if c < 0x20 => return Err("control character in a string".into()),
                        c => s.push(c),
                    }
                }
                String::from_utf8(s).map(V::Str).map_err(|_| "string is not UTF-8".into())
            }
            b't' if b[*i..].starts_with(b"true") => {
                *i += 4;
                Ok(V::Bool(true))
            }
            b'f' if b[*i..].starts_with(b"false") => {
                *i += 5;
                Ok(V::Bool(false))
            }
            b'n' if b[*i..].starts_with(b"null") => {
                *i += 4;
                Ok(V::Null)
            }
            b'-' | b'0'..=b'9' => {
                let st = *i;
                while *i < b.len() && matches!(b[*i], b'-' | b'+' | b'.' | b'e' | b'E' | b'0'..=b'9') {
                    *i += 1;
                }
                let t = std::str::from_utf8(&b[st..*i]).unwrap().to_string();
                t.parse::<f64>().map_err(|_| format!("bad number {t}"))?;
                let digits = t.trim_start_matches('-');
                if digits.len() > 1 && digits.starts_with('0') && !digits[1..].starts_with(['.', 'e', 'E']) {
                    return Err(format!("leading zero in {t}"));
                }
                Ok(V::Num(t))
            }
            _ => Err(format!("unexpected {:?} at {i}", c as char)),
        }
    }

    /// Compact JSON text of v (keys in order; strings escaped minimally).
    pub fn dump(v: &V) -> String {
        match v {
            V::Null => "null".into(),
            V::Bool(b) => b.to_string(),
            V::Num(n) => n.clone(),
            V::Str(s) => {
                let mut o = String::from("\"");
                for c in s.chars() {
                    match c {
                        '"' => o.push_str("\\\""),
                        '\\' => o.push_str("\\\\"),
                        c if (c as u32) < 0x20 => o.push_str(&format!("\\u{:04x}", c as u32)),
                        c => o.push(c),
                    }
                }
                o.push('"');
                o
            }
            V::Arr(a) => format!("[{}]", a.iter().map(dump).collect::<Vec<_>>().join(",")),
            V::Obj(kv) => format!("{{{}}}", kv.iter().map(|(k, x)| format!("{}:{}", dump(&V::Str(k.clone())), dump(x))).collect::<Vec<_>>().join(",")),
        }
    }

    /// Checks v against the JSON-schema subset of constrain.pyi.
    pub fn validate(v: &V, s: &V) -> Result<(), String> {
        let get = |k: &str| s.get_opt(k);
        if let Some(e) = get("enum") {
            return if e.arr().contains(v) { Ok(()) } else { Err(format!("{v:?} not in enum")) };
        }
        if let Some(c) = get("const") {
            return if c == v { Ok(()) } else { Err(format!("{v:?} != const")) };
        }
        if let Some(any) = get("anyOf") {
            return if any.arr().iter().any(|x| validate(v, x).is_ok()) { Ok(()) } else { Err(format!("{v:?} matches no anyOf branch")) };
        }
        match (get("type").map(|t| t.str()), v) {
            (Some("string"), V::Str(_)) | (Some("boolean"), V::Bool(_)) | (Some("null"), V::Null) => Ok(()),
            (Some("number"), V::Num(_)) => Ok(()),
            (Some("integer"), V::Num(n)) if !n.contains(['.', 'e', 'E']) => Ok(()),
            (Some("array"), V::Arr(a)) => {
                let lo = get("minItems").map(|x| x.i64()).unwrap_or(0) as usize;
                let hi = get("maxItems").map(|x| x.i64() as usize);
                if a.len() < lo || hi.is_some_and(|h| a.len() > h) {
                    return Err(format!("{} items outside [{lo}, {hi:?}]", a.len()));
                }
                a.iter().try_for_each(|x| validate(x, get("items").unwrap()))
            }
            (Some("object"), V::Obj(kv)) => {
                let empty = V::Obj(Vec::new());
                let props = get("properties").unwrap_or(&empty).obj();
                for (k, x) in kv {
                    let Some((_, ps)) = props.iter().find(|(p, _)| p == k) else { return Err(format!("unexpected key {k}")) };
                    validate(x, ps)?;
                }
                if let Some(r) = get("required") {
                    for name in r.arr() {
                        if !kv.iter().any(|(k, _)| k == name.str()) {
                            return Err(format!("missing required {}", name.str()));
                        }
                    }
                }
                let mut seen = std::collections::HashSet::new();
                if !kv.iter().all(|(k, _)| seen.insert(k.clone())) {
                    return Err("duplicate key".into());
                }
                Ok(())
            }
            (t, v) => Err(format!("{v:?} is not of type {t:?}")),
        }
    }
}
