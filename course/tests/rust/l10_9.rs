fn fixtures() -> PathBuf {
    PathBuf::from(std::env::var("TINYLLM_FIXTURES").expect("TINYLLM_FIXTURES is set by ol"))
}

fn load(rel: &str) -> j::V {
    j::parse(&std::fs::read_to_string(fixtures().join(rel)).unwrap_or_else(|e| panic!("{rel}: {e}")))
}

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
}

fn vocab_of(v: &j::V) -> Vec<Option<Vec<u8>>> {
    v.arr().iter().map(|t| match t {
        j::V::Null => None,
        t => Some(unhex(t.str())),
    }).collect()
}

/// The DFA as the fixture stores it: per state, runs [lo, hi, target].
fn dfa_runs(d: &constrain::Dfa) -> Vec<Vec<[i64; 3]>> {
    (0..d.n_states)
        .map(|s| {
            let row = &d.trans[s * 256..(s + 1) * 256];
            let mut out = Vec::new();
            let mut lo = 0;
            for b in 1..=256 {
                if b == 256 || row[b] != row[lo] {
                    out.push([lo as i64, b as i64 - 1, row[lo] as i64]);
                    lo = b;
                }
            }
            out
        })
        .collect()
}

fn fixture_runs(v: &j::V) -> Vec<Vec<[i64; 3]>> {
    v.arr().iter().map(|row| row.arr().iter().map(|r| {
        let a = r.arr();
        [a[0].i64(), a[1].i64(), a[2].i64()]
    }).collect()).collect()
}

/// Replays recorded paths: at every step the allowed ids and completeness
/// must equal the record, then the recorded token is taken.
fn replay(name: &str, index: &Arc<TokenIndex>, paths: &j::V, eos: u32) {
    for (pi, path) in paths.arr().iter().enumerate() {
        let mut c = Constraint::new(Arc::clone(index));
        for (si, step) in path.arr().iter().enumerate() {
            let want: Vec<u32> = step.get("mask").arr().iter().map(|x| x.i64() as u32).collect();
            let got: Vec<u32> = c.mask().iter().enumerate().filter(|(_, &m)| m).map(|(i, _)| i as u32).collect();
            assert_eq!(got, want, "{name} path {pi} step {si}: allowed tokens");
            assert_eq!(c.is_complete(), step.get("complete").bool(), "{name} path {pi} step {si}: complete");
            if *step.get("token") == j::V::Null {
                assert!(want.is_empty(), "{name}: a path stops only where nothing is allowed");
                break;
            }
            let tok = step.get("token").i64() as u32;
            c.advance(tok).unwrap_or_else(|e| panic!("{name} path {pi} step {si}: {e}"));
            if tok == eos {
                assert!(c.done && c.mask().iter().all(|&m| !m), "{name}: after EOS nothing is allowed");
            }
        }
    }
}

/// xorshift64*: test data only, independent of the code under test.
struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545F4914F6CDD1D)
    }
    fn unit(&mut self) -> f32 {
        (self.next() >> 40) as f32 / (1u64 << 24) as f32
    }
}

/// A random walk under a constraint: random logits (structural bytes and
/// EOS favored so walks end), sampled with constrained_sample. Returns the
/// generated bytes, or None when the walk did not finish in `max` steps.
fn walk(index: &Arc<TokenIndex>, vocab: &[Option<Vec<u8>>], eos: u32, seed: u64, max: usize) -> Option<Vec<u8>> {
    let mut rng = Rng(seed.wrapping_mul(0x9E3779B97F4A7C15) | 1);
    let mut c = Constraint::new(Arc::clone(index));
    let mut pcg = Pcg32::new(seed, 54);
    let mut out = Vec::new();
    let p = SamplingParams::default();
    for _ in 0..max {
        let logits: Vec<f32> = (0..vocab.len())
            .map(|i| {
                let base = rng.unit() * 2.0;
                match vocab[i].as_deref() {
                    _ if i as u32 == eos => base + 8.0,
                    Some(b"\"") | Some(b"}") | Some(b"]") | Some(b",") => base + 2.5,
                    _ => base,
                }
            })
            .collect();
        let (tok, lp) = constrain::constrained_sample(&logits, &mut c, &p, &[], &[], &mut pcg).expect("a live state always allows a token");
        assert!(lp.is_finite() && lp <= 0.0, "logprob {lp}");
        if tok == eos {
            return Some(out);
        }
        out.extend_from_slice(vocab[tok as usize].as_ref().unwrap());
    }
    None
}

