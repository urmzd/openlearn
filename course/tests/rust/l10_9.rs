//! (tl-engine constrain, tl-serve tools).
//!
//! Annotated exemplars (DESIGN 5.12). The Rust automaton is held to your
//! Python L8.7 on shared inputs: course/fixtures/L10.9/constrain_golden.json
//! (course/oracle/L10.9/constrain_golden.py, from the Python reference)
//! records, per schema and pattern, the regex, the canonical DFA, and the
//! masks along seeded paths through a byte-token vocabulary; L8.7's own
