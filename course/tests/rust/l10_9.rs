#[test]
fn token_index_rules() {
    // WHY: the mask's edge cases: a special token (None) and the empty token
    //      are never allowed; EOS only where the prefix is a whole string and
    //      it keeps the state; a forbidden token or anything after EOS is an
    //      error, not a silent state change.
    // KIND: boundary
    // CATCHES: s06, m07, m10
    // CHAPTER: L10.9 section 4
    let vocab: Vec<Option<Vec<u8>>> = vec![Some(b"a".to_vec()), Some(b"ab".to_vec()), None, Some(Vec::new()), Some(b"b".to_vec()), None];
    let idx = Arc::new(TokenIndex::new(constrain::regex_to_dfa("ab?").unwrap(), &vocab, Some(5)).unwrap());
    assert_eq!(idx.mask(0).unwrap(), vec![true, true, false, false, false, false]);
    let s1 = idx.next_state(0, 0).unwrap();
    assert_eq!(idx.mask(s1).unwrap(), vec![false, false, false, false, true, true], "after 'a': 'b' or EOS");
    assert_eq!(idx.next_state(s1, 5).unwrap(), s1, "EOS keeps the state");
    assert_eq!(idx.next_state(0, 5).unwrap(), DEAD, "EOS before a whole string is DEAD");
    assert_eq!(idx.next_state(0, 2).unwrap(), DEAD, "a special is DEAD");
    assert!(idx.next_state(0, 6).is_err() && idx.mask(99).is_err());
    assert!(TokenIndex::new(constrain::regex_to_dfa("a").unwrap(), &vocab, Some(6)).is_err());
    let mut c = Constraint::new(Arc::clone(&idx));
    assert!(c.advance(4).is_err(), "'b' first is forbidden");
    c.advance(0).unwrap();
    assert!(c.is_complete());
    c.advance(5).unwrap();
    assert!(c.done && c.advance(4).is_err());
}

#[test]
fn constrained_sample_hand_example() {
    // WHY: the mask comes before the sampler, and the logprob is the masked
    //      distribution's. Pattern ab?, vocabulary [a b c EOS], logits
    //      [0 1 5 2]: in state 0 only a is allowed, so greedy takes a (not
    //      the larger c) with logprob 0; then b or EOS: greedy takes EOS
    //      (2 > 1) with logprob 2 - ln(e^1 + e^2).
    // KIND: unit
    // CATCHES: s07, s11, m06, m11
    // CHAPTER: L10.9 section 3
    let vocab = vec![Some(b"a".to_vec()), Some(b"b".to_vec()), Some(b"c".to_vec()), None];
    let idx = Arc::new(TokenIndex::new(constrain::regex_to_dfa("ab?").unwrap(), &vocab, Some(3)).unwrap());
    let mut c = Constraint::new(idx);
    let mut rng = Pcg32::new(0, 54);
    let logits = [0.0f32, 1.0, 5.0, 2.0];
    let (t, lp) = constrain::constrained_sample(&logits, &mut c, &SamplingParams::greedy(), &[], &[], &mut rng).unwrap();
    assert_eq!((t, lp), (0, 0.0));
    let (t, lp) = constrain::constrained_sample(&logits, &mut c, &SamplingParams::greedy(), &[], &[], &mut rng).unwrap();
    assert_eq!(t, 3);
    assert!((lp - (2.0 - (1f64.exp() + 2f64.exp()).ln())).abs() < 1e-12, "logprob {lp}");
    assert!(constrain::apply_mask(&logits, &[false; 4]).is_err(), "a mask that allows nothing is an error");
}

#[test]
fn constrained_output_always_parses() {
    // WHY: the point of constraining: whatever the logits, the finished
    //      output is valid JSON that satisfies the schema. 25 seeded random
    //      walks per fixture schema through the byte-token vocabulary, each
    //      parsed and validated by the test's own JSON reader and validator.
    // KIND: property
    // CATCHES: s03, s04, s05, s06, m02
    // CHAPTER: L10.9 section 2
    let g = load("L10.9/constrain_golden.json");
    let vocab = vocab_of(g.get("vocab"));
    let eos = g.get("eos_id").i64() as u32;
    for c in g.get("schemas").arr() {
        let name = c.get("name").str();
        let schema = j::parse(c.get("schema").str());
        let pat = constrain::json_schema_to_regex(&Json::parse(c.get("schema").str()).unwrap()).unwrap();
        let idx = Arc::new(TokenIndex::new(constrain::regex_to_dfa(&pat).unwrap(), &vocab, Some(eos)).unwrap());
        for seed in 0..25u64 {
            let out = walk(&idx, &vocab, eos, seed, 600).unwrap_or_else(|| panic!("{name} seed {seed}: no EOS in 600 steps"));
            let text = String::from_utf8(out.clone()).unwrap_or_else(|_| panic!("{name} seed {seed}: not UTF-8: {out:?}"));
            let v = j::try_parse(&text).unwrap_or_else(|e| panic!("{name} seed {seed}: {text:?} is not JSON: {e}"));
            if let Err(e) = j::validate(&v, &schema) {
                panic!("{name} seed {seed}: {text} breaks the schema: {e}");
            }
        }
    }
}

#[test]
fn json_object_grammar() {
    // WHY: response_format json_object asks for any JSON object, which no
    //      regular language describes exactly; the grammar bounds the
    //      nesting (3 levels). It accepts objects up to that depth and
    //      rejects arrays, scalars, and broken objects.
    // KIND: boundary
    // CATCHES: s01, m01, m05, m12
    // CHAPTER: L10.9 section 4
    let d = constrain::regex_to_dfa(&constrain::json_object_regex(3)).unwrap();
    for ok in [&b"{}"[..], br#"{"a":1}"#, br#"{"a":[1,{"b":null}],"c":"\u00e9"}"#, br#"{"x":{"y":{"z":true}}}"#] {
        assert!(d.matches(ok), "{} must match", String::from_utf8_lossy(ok));
    }
    for bad in [&b"[]"[..], b"1", br#"{"a":}"#, br#"{"a":1,}"#, br#"{a:1}"#, br#"{"x":{"y":{"z":{"w":1}}}}"#] {
        assert!(!d.matches(bad), "{} must not match", String::from_utf8_lossy(bad));
    }
}

