fn feed(p: &mut ToolParser, pieces: &[&str]) -> Vec<ToolEvent> {
    let mut ev = Vec::new();
    for x in pieces {
        ev.extend(p.push(x));
    }
    ev.extend(p.finish());
    ev
}

