#[test]
fn hand_example_dfa() {
    // WHY: the chapter's worked automaton for (cat|car|dog)s?. Breadth-first
    //      from state 0 with bytes in order: c -> 1, d -> 2; from 1, a -> 3;
    //      from 2, o -> 4; "car", "cat", and "dog" all reach the same
    //      accepting state 5 (minimization merges them); s -> 6. Seven states,
    //      accepting {5, 6}; every other byte is DEAD.
    // KIND: unit
    // CATCHES: m01, m05
    // CHAPTER: L10.9 section 3
    let d = constrain::regex_to_dfa("(cat|car|dog)s?").unwrap();
    assert_eq!(d.n_states, 7);
    assert_eq!(d.accept, vec![false, false, false, false, false, true, true]);
    let t = |s: usize, b: u8| d.trans[s * 256 + b as usize];
    assert_eq!((t(0, b'c'), t(0, b'd'), t(1, b'a'), t(2, b'o')), (1, 2, 3, 4));
    assert_eq!((t(3, b't'), t(3, b'r'), t(4, b'g'), t(5, b's')), (5, 5, 5, 6));
    assert_eq!(d.trans.iter().filter(|&&x| x != DEAD).count(), 8, "only the 8 edges above are live");
    assert!(d.matches(b"cats") && d.matches(b"dog") && !d.matches(b"ca") && !d.matches(b"dogss"));
    assert_eq!(d.step(0, b"cax").unwrap(), DEAD);
    assert_eq!(d.step(DEAD, b"c").unwrap(), DEAD);
    assert!(d.step(7, b"c").is_err());
}

